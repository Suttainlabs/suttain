// ── Engine-specific input file templates ────────────────────────────
// Generates structured, ready-to-run input files for computational
// chemistry engines. Each file includes realistic parameters derived
// from the user's simulation configuration and environmental conditions.

function genORCA(inputs, env) {
  const functional = inputs.functional || 'B3LYP';
  const basis = inputs.basis_set || 'def2-TZVP';
  const task = (inputs.task || 'geometry optimization').toLowerCase();
  const molecule = inputs.molecule || 'H2O';

  let keyword = '! ';
  if (task.includes('optim')) keyword += 'OPT ';
  if (task.includes('freq')) keyword += 'FREQ ';
  if (task.includes('nmr')) keyword += 'NMR ';
  if (task.includes('single point') || task.includes('sp')) keyword += 'SP ';
  keyword += `${functional} ${basis} TightSCF`;
  if (env.solvent && env.solvent !== 'none' && env.solvent !== 'vacuum') {
    keyword += ' CPCM(WATER)';
  }

  const charge = inputs.charge || 0;
  const mult = inputs.multiplicity || 1;

  let content = `${keyword}
%maxcore 4000
%pal nprocs 8 end

* xyz ${charge} ${mult}
${molecule}
*`;

  return [{
    filename: 'orca_input.inp',
    content,
    description: `ORCA input file — ${functional}/${basis}, ${task}. Run with: orca orca_input.inp`
  }];
}

function genGROMACS(inputs, env) {
  const ff = inputs.force_field || env.forcefield || 'AMBER99SB-ILDN';
  const temp = inputs.temperature || env.temperature || 300;
  const time = inputs.simulation_time || '100 ns';
  const system = inputs.system || 'Protein in water';

  const nsteps = time.includes('ns') ? parseInt(time) * 500000 : 50000000;

  const mdp = `; GROMACS .mdp file — generated by Suttain
; System: ${system}
; Force field: ${ff}
; Temperature: ${temp} K

integrator = md
nsteps = ${nsteps}
dt = 0.002

; Output control
nstxout = 0
nstvout = 0
nstfout = 0
nstxout-compressed = 5000
nstenergy = 5000
nstlog = 5000

; Bond parameters
continuation = yes
constraint_algorithm = lincs
constraints = h-bonds
lincs_iter = 1
lincs_order = 4

; Neighborsearching
cutoff-scheme = Verlet
ns_type = grid
nstlist = 10
rcoulomb = 1.0
rvdw = 1.0

; Electrostatics
coulombtype = PME
pme_order = 4
fourierspacing = 0.16

; Temperature coupling
tcoupl = V-rescale
tc-grps = Protein Non-Protein
tau_t = 0.1 0.1
ref_t = ${temp} ${temp}

; Pressure coupling
pcoupl = Parrinello-Rahman
pcoupltype = isotropic
tau_p = 2.0
ref_p = ${env.pressure || 1.0}
compressibility = 4.5e-5

; PBC
pbc = xyz

; Dispersion correction
DispCorr = EnerPres

; Velocity generation
gen_vel = no`;

  return [{
    filename: 'gromacs.mdp',
    content: mdp,
    description: `GROMACS MDP file — ${ff}, ${temp}K, ${time}. Run: gmx grompp -f gromacs.mdp -o topol.tpr`
  }];
}

function genVASP(inputs, env) {
  const functional = inputs.functional || 'PBE';
  const kpoints = inputs.kpoints || '4x4x4';
  const property = inputs.property || 'Band gap';
  const material = inputs.material || 'Si';

  const encut = functional.includes('HSE') ? 520 : 450;
  const isHSE = functional.includes('HSE');
  const isOpt = property.toLowerCase().includes('optim') || property.toLowerCase().includes('formation');

  const incar = `# VASP INCAR — generated by Suttain
# Material: ${material}
# Functional: ${functional}
# Property: ${property}

SYSTEM = ${material}
PREC = Accurate
ENCUT = ${encut}
EDIFF = 1E-6
EDIFFG = -0.01
${isOpt ? 'IBRION = 2\nNSW = 100\nISIF = 3' : 'IBRION = -1\nNSW = 0'}
ISMEAR = 0
SIGMA = 0.05
LREAL = Auto
LWAVE = .FALSE.
LCHARG = .TRUE.
${isHSE ? 'LHFCALC = .TRUE.\nGGA = PE\nHFSCREEN = 0.2\nALGO = Damped\nTIME = 0.4' : '# GGA = PE'}
${property.includes('DOS') || property.includes('Band') ? 'LORBIT = 11\nICHARG = 2' : ''}
${property.includes('Band structure') ? 'ICHARG = 11' : ''}
${property.includes('Phonon') ? 'IBRION = 6\nNFREE = 2\nPOTIM = 0.015\nNSW = 1' : ''}
${property.includes('Magnetic') ? 'ISPIN = 2\nMAGMOM = 5*2.0' : ''}
${property.includes('Dielectric') ? 'LEPSILON = .TRUE.' : ''}`;

  const kpointsContent = `Automatic mesh
0
Gamma
${kpoints.split('x').join(' ')}
0 0 0`;

  return [
    { filename: 'INCAR', content: incar, description: `VASP INCAR — ${functional}, ${property}` },
    { filename: 'KPOINTS', content: kpointsContent, description: `K-point mesh: ${kpoints}` },
  ];
}

