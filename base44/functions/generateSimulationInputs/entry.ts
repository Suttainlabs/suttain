function genLAMMPS(inputs, env) {
  const temp = inputs.temperature || env.temperature || 300;
  const system = inputs.system || 'Material system';

  const content = `# LAMMPS input — generated by Suttain
# System: ${system}
# Temperature: ${temp} K

units metal
atom_style atomic
boundary p p p

# Read structure
read_data structure.data

# Interatomic potential
pair_style eam/alloy
pair_coeff * * potential.eam.alloy

# Neighbor list
neighbor 2.0 bin
neigh_modify delay 5

# Minimization
min_style cg
minimize 1e-6 1e-8 1000 10000

# Reset timestep
reset_timestep 0

# Thermodynamic output
thermo 100
thermo_style custom step temp pe ke etotal press vol

# Temperature initialization
velocity all create ${temp} 12345 mom yes rot no dist gaussian

# NPT ensemble
fix 1 all npt temp ${temp} ${temp} 0.1 iso 1.0 1.0 1.0

# Output trajectory
dump 1 all custom 1000 trajectory.lammpstrj id type x y z

# Run
timestep 0.001
run 100000`;

  return [{
    filename: 'lammps.in',
    content,
    description: `LAMMPS input — NPT MD at ${temp}K. Run: lmp -in lammps.in`
  }];
}

